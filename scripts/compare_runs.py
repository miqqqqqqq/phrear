"""Compare two runs of a Phrear project: heads and MODFLOW 6 input files.

    pixi run compare-runs <project>/runs/<run A> <project>/runs/<run B>

Used for the acceptance of M1b: the example project run from the QGIS plugin
must give the same results as the one run from the command line. Two runs of the
same project content are compared exactly:

- ``gwf.hds``, the binary heads written by MODFLOW 6, byte by byte;
- every variable of ``heads.nc``, value by value (missing values match);
- the MODFLOW 6 input files line by line, except the header comment in which
  FloPy writes the time of writing.

Listing, manifest and the attributes of ``heads.nc`` contain times, names and
paths of the run, so they are not compared. Exit code 0 when the runs are
identical, 1 otherwise.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import xarray as xr

HEADS_BINARY = "gwf.hds"
HEADS_NETCDF = "heads.nc"
#: Files of a run folder that are not MODFLOW 6 input.
NOT_INPUT = {
    ".lst", ".txt", ".json", ".nc", ".hds", ".cbc", ".grb", ".csv"
}  # fmt: skip
FLOPY_HEADER = "# File generated by Flopy"


@dataclass
class Comparison:
    values: int = 0
    """Head values compared in ``heads.nc``."""
    variables: list[str] = field(default_factory=list)
    input_files: list[str] = field(default_factory=list)
    differences: list[str] = field(default_factory=list)

    @property
    def identical(self) -> bool:
        return not self.differences


def _input_lines(path: Path) -> list[str]:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    return [line for line in lines if not line.startswith(FLOPY_HEADER)]


def compare_heads_netcdf(a: Path, b: Path, result: Comparison) -> None:
    with xr.open_dataset(a) as first, xr.open_dataset(b) as second:
        names_a = {str(n) for n in first.data_vars}
        names_b = {str(n) for n in second.data_vars}
        if names_a != names_b:
            result.differences.append(
                f"{HEADS_NETCDF}: variables differ: {sorted(names_a ^ names_b)}"
            )
        if not np.array_equal(first["time"].values, second["time"].values):
            result.differences.append(f"{HEADS_NETCDF}: times differ")
        for name in sorted(names_a & names_b):
            x, y = first[name].values, second[name].values
            result.variables.append(name)
            if x.shape != y.shape:
                result.differences.append(
                    f"{HEADS_NETCDF}: {name} has shape {x.shape} and {y.shape}"
                )
                continue
            numeric = np.issubdtype(x.dtype, np.number)
            same = np.array_equal(x, y, equal_nan=True) if numeric else np.array_equal(x, y)
            if name.startswith("head"):
                result.values += int(np.size(x))
            if not same:
                diff = np.nanmax(np.abs(x - y)) if numeric else "-"
                result.differences.append(f"{HEADS_NETCDF}: {name} differs (max |Δ| = {diff})")


def compare_runs(a: Path, b: Path) -> Comparison:
    result = Comparison()
    for name in (HEADS_BINARY, HEADS_NETCDF):
        for folder in (a, b):
            if not (folder / name).is_file():
                result.differences.append(f"{folder / name} is missing")
    if result.differences:
        return result
    if (a / HEADS_BINARY).read_bytes() != (b / HEADS_BINARY).read_bytes():
        result.differences.append(f"{HEADS_BINARY} differs")
    compare_heads_netcdf(a / HEADS_NETCDF, b / HEADS_NETCDF, result)
    inputs_a = {p.name for p in a.iterdir() if p.is_file() and p.suffix not in NOT_INPUT}
    inputs_b = {p.name for p in b.iterdir() if p.is_file() and p.suffix not in NOT_INPUT}
    if inputs_a != inputs_b:
        result.differences.append(f"MF6 input files differ: {sorted(inputs_a ^ inputs_b)}")
    for name in sorted(inputs_a & inputs_b):
        result.input_files.append(name)
        if _input_lines(a / name) != _input_lines(b / name):
            result.differences.append(f"{name} differs")
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("run_a", type=Path, help="folder of the first run")
    parser.add_argument("run_b", type=Path, help="folder of the second run")
    args = parser.parse_args(argv)
    result = compare_runs(args.run_a, args.run_b)
    if result.identical:
        print(
            f"Identical: {result.values} head values in {len(result.variables)} variables, "
            f"{HEADS_BINARY} byte by byte, {len(result.input_files)} MODFLOW 6 input files."
        )
        return 0
    print("Different:")
    for line in result.differences:
        print(f"  {line}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
